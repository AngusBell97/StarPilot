import assert from "node:assert/strict"
import { readFileSync } from "node:fs"
import { normalizeSnapshot, processFeature, processInfo, processRows, processState, displayNumber, heatLevel, managedTitle } from "../web/js/system-monitor-data.js"

const fixture = JSON.parse(readFileSync(new URL("../web/data/system-monitor.sample.json", import.meta.url), "utf8"))
const sample = normalizeSnapshot(fixture)
assert.equal(sample.mode, undefined)
assert.equal(sample.processCount, 6)
assert.equal(sample.cpuPercent, 27.4)
assert.equal(processRows(sample).length, 6)
assert.deepEqual(processRows(sample, { scope: "comma" }).map(p => p.pid), [102, 101, 104, 103])
assert.deepEqual(processRows(sample, { scope: "users" }).map(p => p.pid), [102, 101, 105, 104, 103])
assert.equal(processRows(sample, { scope: "all" }).length, 6)
assert.deepEqual(processRows(sample, { query: "driving model" }).map(p => p.pid), [102])
assert.deepEqual(processRows(sample, { query: "sleeping", scope: "all" }).map(p => p.pid), [102, 104, 2, 103])
assert.deepEqual(processRows(sample, { sort: "cpu", descending: false, scope: "all" }).map(p => p.pid), [104, 105, 101, 102, 2, 103])
assert.equal(processFeature(sample.processes.at(-1)), "")
assert.equal(processState("R"), "Running")
assert.equal(processState("?"), "?")
assert.equal(processState("constructor"), "constructor")
assert.equal(processState("toString"), "toString")
assert.equal(displayNumber(null, "%"), "—")
assert.equal(displayNumber(0, "%"), "0.0%")
assert.equal("category" in processInfo(sample.processes[0]), false)
assert.equal(processInfo({ name: "mystery", kernel: false, state: "S" }).description, "")
assert.equal(sample.commaThermals.maxTempC, 61.4)
assert.equal(sample.externalGpus.length, 1)
assert.equal(sample.externalGpus[0].hotspotC, 78)
assert.equal(sample.externalGpus[0].memoryLimitC, 95)
assert.equal(heatLevel(78, 100), "normal")
assert.equal(heatLevel(90, 100), "warm")
assert.equal(heatLevel(100, 100), "hot")
assert.equal(heatLevel(120, null), "normal")
assert.equal(heatLevel(null, 100), "normal")
const gpus = normalizeSnapshot({ ...fixture, commaThermals: "hot", externalGpus: [
  { kind: "jetlink", name: "JetLink · Orin", status: "bogus", hotspotC: 0, memoryTempC: 400, fanPercent: 120, loadPercent: 55 },
  { kind: "other", name: "x" }, null] })
assert.equal(gpus.commaThermals, null)
assert.equal(gpus.externalGpus.length, 1)
assert.equal(gpus.externalGpus[0].status, "idle")
assert.equal(gpus.externalGpus[0].hotspotC, null)
assert.equal(gpus.externalGpus[0].memoryTempC, null)
assert.equal(gpus.externalGpus[0].fanPercent, null)
assert.equal(gpus.externalGpus[0].loadPercent, 55)
assert.deepEqual(normalizeSnapshot({ ...fixture, externalGpus: undefined }).externalGpus, [])
assert.throws(() => normalizeSnapshot({ ...fixture, cores: null }), /Invalid/)
assert.throws(() => normalizeSnapshot({ ...fixture, processes: [{ pid: 1 }] }), /Invalid/)
assert.throws(() => normalizeSnapshot({ ...fixture, cores: [fixture.cores[0], fixture.cores[0]] }), /Duplicate/)
assert.throws(() => normalizeSnapshot({ ...fixture, processes: [fixture.processes[0], fixture.processes[0]] }), /Duplicate/)
const withUnknowns = normalizeSnapshot({ ...fixture, cpuPercent: -1,
  processes: [{ ...fixture.processes[0], cpu: Infinity, memoryMiB: "0" }] })
assert.equal(withUnknowns.cpuPercent, null)
assert.equal(withUnknowns.processes[0].cpu, null)
assert.equal(withUnknowns.processes[0].memoryMiB, null)
const impossible = normalizeSnapshot({ ...fixture,
  memory: { ...fixture.memory, usedMiB: fixture.memory.totalMiB + 1 },
  storage: { usedGiB: 200, totalGiB: 100 } })
assert.equal(impossible.memory.usedMiB, null)
assert.equal(impossible.memory.percent, null)
assert.equal(impossible.storage.usedGiB, null)
// openpilot's own processes, process ages, the process manager's view and the GPU peaks
assert.deepEqual(processRows(sample, { scope: "openpilot" }).map(p => p.pid), [102, 101, 105, 104, 103])
assert.deepEqual(processRows(sample, { scope: "all", sort: "ageSeconds" }).map(p => p.pid), [2, 105, 103, 102, 101, 104])
assert.equal(sample.processes.find(p => p.pid === 101).managedName, "controlsd")
assert.equal(sample.processes.find(p => p.pid === 2).openpilot, false)
assert.deepEqual(sample.managed, { expected: 18, running: 18, stopped: [] })
assert.deepEqual(normalizeSnapshot({ ...fixture, managed: { expected: 3, running: 2, stopped: [{ name: "updated", exitCode: 1 }, { exitCode: 2 }] } }).managed,
  { expected: 3, running: 2, stopped: [{ name: "updated", exitCode: 1 }] })
assert.equal(normalizeSnapshot({ ...fixture, managed: { expected: -1 } }).managed, null)
assert.equal(managedTitle("controlsd"), "Steering and speed control")
assert.equal(managedTitle("galaxy"), "Galaxy web interface")
assert.equal(managedTitle("unknownd"), "unknownd")
assert.deepEqual(sample.externalGpus[0].hotspotPeak, { value: 86, at: 1789991000 })
assert.equal(sample.externalGpus[0].peaksResettable, true)
const badPeaks = normalizeSnapshot({ ...fixture, externalGpus: [{ ...fixture.externalGpus[0], hotspotPeak: { value: 900, at: 1 }, memoryPeak: "hot" }] })
assert.equal(badPeaks.externalGpus[0].hotspotPeak, null)
assert.equal(badPeaks.externalGpus[0].memoryPeak, null)
assert.equal(sample.batteryVoltage, 13.3)
console.log("System Monitor data contract: pass")

assert.equal(normalizeSnapshot({...fixture,batteryVoltage:12.64}).batteryVoltage,12.64)
for (const bad of [null,undefined,'12.6',NaN,Infinity,0,-12,10000]) {
  assert.equal(normalizeSnapshot({...fixture,batteryVoltage:bad}).batteryVoltage,null)
}
